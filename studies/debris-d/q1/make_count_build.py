"""make_count_build.py - DEBRIS-D, Q1 (cft-debris, MIT).

Writes count_kernels.inc into DEBRIS-D's scratch: copies of this
repository's own force kernels with every `double` turned into `cnum`, the
counting number type of count_ops.cpp, so that each operation class is
counted by the operator or function it goes through. Nothing is retyped:
each function is taken whole from its file by its name (brace matching).
  - DEBRIS-C's normalised gravity kernel: studies/debris-c/m1a/m1a_grav.c,
    tables() and grav(), with its globals;
  - DEBRIS-B's kernels: studies/debris-b/q2/q2bench.c, the Chebyshev
    reader (cheb_body, cheb_sun_moon), the interpolated frame (rot_x,
    rot_y, rot_z, ident, c2t_from_xys, xys_interp, frame_interp), the
    exponential atmosphere and drag (atmos_drag) and radiation pressure
    with a conical shadow (srp_conical), with their globals.
With --plant, one extra term is written into grav() after its az line for
m = 0: `az -= FZ[n][0] * C0 * V[n + 1][0];` once more, which must add
exactly 2 multiplications and 1 subtraction a degree (the control).

usage: python -I -B make_count_build.py <out.inc> [--plant]
"""
import re
import sys

ROOT = "C:/Users/logan/source/repos/cft-debris/studies"
M1A = ROOT + "/debris-c/m1a/m1a_grav.c"
Q2B = ROOT + "/debris-b/q2/q2bench.c"


def func(text, name):
    m = re.search(r"^static[^\n]*\b%s\(" % re.escape(name), text, re.M)
    if not m:
        raise SystemExit("no function " + name)
    i = text.index("{", m.end())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[m.start():j + 1]
    raise SystemExit("unbalanced " + name)


def lines_matching(text, pats):
    out = []
    for ln in text.splitlines():
        if any(re.match(p, ln) for p in pats):
            out.append(ln)
    return out


def main():
    out, plant = sys.argv[1], "--plant" in sys.argv[2:]
    a = open(M1A).read()
    b = open(Q2B).read()
    parts = ["/* generated by make_count_build.py from this repository's own kernels; do not edit */"]
    # --- DEBRIS-C's gravity
    parts.append("namespace gravc {")
    parts += lines_matching(a, [r"#define NMAXC", r"#define NA ", r"static double Cb\[", r"static int seen",
                                r"static double GM = ", r"static double An\[", r"static double FA\[",
                                r"static double V\["])
    parts.append(func(a, "tables"))
    g = func(a, "grav")
    if plant:
        anchor = "        az -= FZ[n][0] * C0 * V[n + 1][0];\n"
        if g.count(anchor) != 1:
            raise SystemExit("plant anchor not unique")
        g = g.replace(anchor, anchor + "        az -= FZ[n][0] * C0 * V[n + 1][0]; /* PLANTED */\n")
    parts.append(g)
    parts.append("}")
    parts.append("#undef NA")
    # --- DEBRIS-B's kernels
    parts.append("namespace q2b {")
    parts += lines_matching(b, [r"#define GM_EARTH", r"#define R_EARTH", r"#define NEOP", r"#define NNODE"])
    keep = [r"typedef struct \{ const char \*name; int ncoef", r"static ChebBody (MOON|SUN|EMB) =",
            r"static const double EMRAT", r"static double EOP\[", r"static const double T_EPOCH_JD",
            r"static double NODE_DT;", r"static double NODE\[", r"static const double ATM_",
            r"static const double OMEGA_E", r"static const double R_SUN"]
    body = b.splitlines()
    for i, ln in enumerate(body):
        if any(re.match(p, ln) for p in keep):
            # a declaration may continue over lines until its ';'
            j = i
            chunk = [ln]
            while not chunk[-1].rstrip().endswith(";"):
                j += 1
                chunk.append(body[j])
            parts += chunk
    for name in ["cheb_body", "cheb_sun_moon", "rot_x", "rot_y", "rot_z", "ident", "c2t_from_xys",
                 "xys_interp", "frame_interp", "atmos_drag", "srp_conical"]:
        parts.append(func(b, name))
    parts.append("}")
    text = "\n".join(parts) + "\n"
    text = re.sub(r"\bdouble\b", "cnum", text)
    open(out, "w", newline="\n").write(text)
    print("wrote %s (%d lines)%s" % (out, text.count("\n"), " with the plant" if plant else ""))


if __name__ == "__main__":
    main()
