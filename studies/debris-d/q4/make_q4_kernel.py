"""make_q4_kernel.py - DEBRIS-D, Q4 (cft-debris, MIT).

Writes q4_kernel.inc into DEBRIS-D's scratch: DEBRIS-C's normalised
gravity kernel (studies/debris-c/m1a/m1a_grav.c, its globals, tables() and
grav(), taken whole by name) with every `double` turned into `REAL`, so
q4prop.c can run the same kernel at binary64 and at x87 extended precision
(long double). Nothing is retyped.

usage: python -I -B make_q4_kernel.py <out.inc>
"""
import re
import sys

M1A = "C:/Users/logan/source/repos/cft-debris/studies/debris-c/m1a/m1a_grav.c"


def func(text, name):
    m = re.search(r"^static[^\n]*\b%s\(" % re.escape(name), text, re.M)
    i = text.index("{", m.end())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[m.start():j + 1]
    raise SystemExit("unbalanced " + name)


def main():
    a = open(M1A).read()
    parts = ["/* generated by make_q4_kernel.py from studies/debris-c/m1a/m1a_grav.c; do not edit */"]
    for ln in a.splitlines():
        if any(re.match(p, ln) for p in [r"#define NMAXC", r"#define NA ", r"static double Cb\[", r"static int seen",
                                          r"static double GM = ", r"static double An\[", r"static double FA\[",
                                          r"static double V\["]):
            parts.append(ln)
    parts.append(func(a, "tables"))
    parts.append(func(a, "grav"))
    text = re.sub(r"\bdouble\b", "REAL", "\n".join(parts) + "\n")
    open(sys.argv[1], "w", newline="\n").write(text)
    print("wrote", sys.argv[1])


if __name__ == "__main__":
    main()
