GLYPHS = {}
for _c, _s in _G.items():
    _rows = _s.split("/")
    assert len(_rows) == 7 and all(len(r) == 5 or _c == " " for r in _rows), _c
    GLYPHS[_c] = np.array([[1 if ch == "#" else 0 for ch in (r + "....." )[:5]] for r in _rows], dtype=bool)


def text_mask(s, scale=2, gap=1):
    """boolean mask (7*scale, n) of the string s, one column of gap between glyphs; unknown characters are a blank box"""
    cols = []
    for ch in s:
        g = GLYPHS.get(ch if ch in GLYPHS else ch.upper(), None)
        if g is None:
            g = np.zeros((7, 5), dtype=bool)
            g[0, :] = g[6, :] = g[:, 0] = g[:, 4] = True
        cols.append(np.kron(g, np.ones((scale, scale), dtype=bool)))
        cols.append(np.zeros((7 * scale, gap * scale), dtype=bool))
    return np.hstack(cols) if cols else np.zeros((7 * scale, 0), dtype=bool)


def draw_text(img, x, y, s, color, scale=2):
    """paint the string s with its top-left at column x, row y (clipped to the image); returns the mask's width"""
    m = text_mask(s, scale)
    h, w = m.shape
    H, W = img.shape[:2]
    y0, y1, x0, x1 = max(y, 0), min(y + h, H), max(x, 0), min(x + w, W)
    if y1 > y0 and x1 > x0:
        sub = m[y0 - y:y1 - y, x0 - x:x1 - x]
        img[y0:y1, x0:x1][sub] = color
    return w
